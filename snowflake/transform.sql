-- Snowflake version of the SQLite prep in claims_model/data.py; runs after CLAIMS.RAW.POLICIES is loaded.

-- modelling table with the same caps as the SQLite version
CREATE OR REPLACE TABLE CLAIMS.ANALYTICS.MODEL_TABLE AS
SELECT
    CAST(IDPOL AS INTEGER)          AS POLICY_ID,
    LEAST(CLAIMNB, 4)               AS CLAIMS,
    LEAST(EXPOSURE, 1.0)            AS EXPOSURE,
    AREA,
    LEAST(VEHPOWER, 12)             AS VEH_POWER,
    LEAST(VEHAGE, 20)               AS VEH_AGE,
    LEAST(DRIVAGE, 90)              AS DRIV_AGE,
    LEAST(BONUSMALUS, 150)          AS BONUS_MALUS,
    VEHBRAND                        AS VEH_BRAND,
    REPLACE(VEHGAS, '''', '')       AS VEH_GAS,
    DENSITY,
    REGION
FROM CLAIMS.RAW.POLICIES
WHERE EXPOSURE > 0;

-- data-quality checks, one row per check
CREATE OR REPLACE VIEW CLAIMS.ANALYTICS.DATA_QUALITY AS
SELECT 'rows' AS CHECK_NAME, COUNT(*) AS VALUE FROM CLAIMS.RAW.POLICIES
UNION ALL SELECT 'duplicate_policy_ids', COUNT(*) - COUNT(DISTINCT IDPOL) FROM CLAIMS.RAW.POLICIES
UNION ALL SELECT 'null_cells',
    COUNT_IF(IDPOL IS NULL) + COUNT_IF(CLAIMNB IS NULL) + COUNT_IF(EXPOSURE IS NULL) + COUNT_IF(AREA IS NULL)
  + COUNT_IF(VEHPOWER IS NULL) + COUNT_IF(VEHAGE IS NULL) + COUNT_IF(DRIVAGE IS NULL) + COUNT_IF(BONUSMALUS IS NULL)
  + COUNT_IF(VEHBRAND IS NULL) + COUNT_IF(VEHGAS IS NULL) + COUNT_IF(DENSITY IS NULL) + COUNT_IF(REGION IS NULL)
  FROM CLAIMS.RAW.POLICIES
UNION ALL SELECT 'non_positive_exposure', COUNT_IF(EXPOSURE <= 0) FROM CLAIMS.RAW.POLICIES
UNION ALL SELECT 'exposure_over_one_year', COUNT_IF(EXPOSURE > 1) FROM CLAIMS.RAW.POLICIES
UNION ALL SELECT 'claims_over_four', COUNT_IF(CLAIMNB > 4) FROM CLAIMS.RAW.POLICIES;

-- observed frequency by bonus-malus band
CREATE OR REPLACE VIEW CLAIMS.ANALYTICS.FREQ_BY_BONUS_MALUS AS
SELECT
    CASE
        WHEN BONUS_MALUS < 60  THEN '50-59'
        WHEN BONUS_MALUS < 80  THEN '60-79'
        WHEN BONUS_MALUS < 100 THEN '80-99'
        ELSE '100+'
    END                                     AS BONUS_MALUS_BAND,
    COUNT(*)                                AS POLICIES,
    ROUND(SUM(EXPOSURE), 0)                 AS EXPOSURE_YEARS,
    SUM(CLAIMS)                             AS CLAIMS,
    ROUND(SUM(CLAIMS) / SUM(EXPOSURE), 4)   AS CLAIM_FREQUENCY
FROM CLAIMS.ANALYTICS.MODEL_TABLE
GROUP BY BONUS_MALUS_BAND
ORDER BY MIN(BONUS_MALUS);
